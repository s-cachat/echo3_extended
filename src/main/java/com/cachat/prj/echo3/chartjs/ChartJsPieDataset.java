    private Double offset;
    private Double rotation;
    private Double spacing;
    private Double radius;
    private Double weight = 1.0;

    public ChartJsBorderAlign getBorderAlign() {
        return borderAlign;
    }

    public void setBorderAlign(ChartJsBorderAlign borderAlign) {
        this.borderAlign = borderAlign;
    }

    public List<Double> getBorderDash() {
        return borderDash;
    }

    public void setBorderDash(List<Double> borderDash) {
        this.borderDash = borderDash;
    }

    public Double getBorderDashOffset() {
        return borderDashOffset;
    }

    public void setBorderDashOffset(Double borderDashOffset) {
        this.borderDashOffset = borderDashOffset;
    }

    public ChartJsBorderJoinStyle getBorderJoinStyle() {
        return borderJoinStyle;
    }

    public void setBorderJoinStyle(ChartJsBorderJoinStyle borderJoinStyle) {
        this.borderJoinStyle = borderJoinStyle;
    }

    public Double getBorderRadius() {
        return borderRadius;
    }

    public void setBorderRadius(Double borderRadius) {
        this.borderRadius = borderRadius;
    }

    public Double getCircumference() {
        return circumference;
    }

    public void setCircumference(Double circumference) {
        this.circumference = circumference;
    }

    public List<Double> getHoverBorderDash() {
        return hoverBorderDash;
    }

    public void setHoverBorderDash(List<Double> hoverBorderDash) {
        this.hoverBorderDash = hoverBorderDash;
    }

    public Double getHoverBorderDashOffset() {
        return hoverBorderDashOffset;
    }

    public void setHoverBorderDashOffset(Double hoverBorderDashOffset) {
        this.hoverBorderDashOffset = hoverBorderDashOffset;
    }

