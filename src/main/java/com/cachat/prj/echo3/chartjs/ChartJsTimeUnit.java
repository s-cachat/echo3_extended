package com.cachat.prj.echo3.chartjs;

/**
 * The following time measurements are supported. The names can be passed as
 * strings to the time.unit config option to force a certain unit.
 *
 * @author scachat
 */
public enum ChartJsTimeUnit {
    MILLISECOND,
    SECOND,
    MINUTE,
    HOUR,
    DAY,
    WEEK,
    MONTH,
    QUARTER,
    YEAR,
}
